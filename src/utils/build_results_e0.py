# --------------------------------------------------------------------------- the sweep


def sweep_acc(variant: str, k1: float, b: float, queryset: str, dup: set[str]) -> float | None:
    path = RUNS / queryset / f"{variant}__k1-{k1:.2f}__b-{b:.2f}__OE"
    if not (path / "results_perquery.parquet").is_file():
        return None
    frame = pd.read_parquet(path / "results_perquery.parquet")
    return float(frame[~frame["gold_item_key"].isin(dup)]["item_acc1"].mean())


def write_transferability(dup: set[str]) -> None:
    lines = header(
        "the `k1`/`b` transferability verdict (dev)",
        [
            "`k1`=0.60 / `b`=0.35 was fitted to OEB `resumen` queries of ~14 tokens; OE `texto`",
            "queries run ~74–78. 25 points × 2 field variants × 3 query sets, 150 cells, each point",
            "with its own index because BM25 bakes both parameters into the document weights.",
            "**This is tuning, so it touches dev only.**",
        ],
    )
    lines.append("## Verdict: the operating point transfers (D-036)")
    lines.append("")
    rows = []
    for variant in SWEEP_VARIANTS:
        for queryset in SWEEP_SETS:
            surface = {
                (k1, b): sweep_acc(variant, k1, b, queryset, dup)
                for k1 in K1_VALUES
                for b in B_VALUES
            }
            surface = {k: v for k, v in surface.items() if v is not None}
            best = max(surface, key=surface.get)
            ref = surface[TRANSFERRED]
            delta_ci = ""
            p_str = ""
            if best != TRANSFERRED:
                a = pd.read_parquet(RUNS / queryset / f"{variant}__k1-{best[0]:.2f}__b-{best[1]:.2f}__OE" / "results_perquery.parquet")
                r = pd.read_parquet(RUNS / queryset / f"{variant}__k1-{TRANSFERRED[0]:.2f}__b-{TRANSFERRED[1]:.2f}__OE" / "results_perquery.parquet")
                m = a[["query_item_key", "gold_item_key", "gold_parent_key", "item_acc1"]].merge(
                    r[["query_item_key", "item_acc1"]], on="query_item_key",
                    suffixes=("_a", "_r"), validate="one_to_one")
                m = m[~m["gold_item_key"].isin(dup)]
                d = (m["item_acc1_a"] - m["item_acc1_r"]).to_numpy(float)
                draws = boot_query(np.column_stack([d]), f"sweep|{variant}|{queryset}")
                delta_ci = fci(ci(draws[:, 0]), signed=True)
                p_str = fp(boot_p(draws[:, 0]))
                flips = f"+{int((d > 0).sum())} / −{int((d < 0).sum())}"
            else:
                delta_ci, p_str, flips = "—", "—", "—"
            rows.append(
                f"| `{variant}` | `{queryset}` | {best[0]:.2f} / {best[1]:.2f} | {f4(surface[best])} | "
                f"{f4(ref)} | {fd(surface[best] - ref)} | {delta_ci} | {p_str} | {flips} |"
            )
    lines += [
        "| variant | query set | argmax | its Acc@1 | 0.60/0.35 | Δ | CI (paired) | p | queries up / down |",
        "|---|---|---|---:|---:|---:|---|---:|---|",
        *rows,
        "",
        "**In 4 of 6 cells the argmax *is* the transferred point.** In the two where it is not, the "
        "paired contrast straddles 0 and the flip counts are near-symmetric: those settings reshuffle "
        "which queries succeed rather than retrieving better. Both variants therefore keep "
        "**0.60 / 0.35** into S4 (D-036, referred to César because the frozen rule names the argmax "
        "and S2 rejected D-027 for reinterpreting a rule after seeing results).",
        "",
        "This is a **negative result in the useful sense**: it removes a threat to the previous study's "
        "tuning instead of confirming one. Whatever is wrong with the 0.974 headline, it is not the "
        "operating point.",
        "",
        "## The surfaces",
        "",
        "Item Acc@1 on the duplicate-free population. `b` dominates, more length normalisation "
        "monotonically hurts, low `k1` wins, and both variants agree — a smooth surface with its "
        "optimum in the low-`k1`/low-`b` corner, not a knife-edge.",
        "",
    ]
    for variant in SWEEP_VARIANTS:
        for queryset in SWEEP_SETS:
            lines += [f"**`{variant}` / `{queryset}`**", "",
                      "| | " + " | ".join(f"b={b:.2f}" for b in B_VALUES) + " |",
                      "|---|" + "---:|" * len(B_VALUES)]
            for k1 in K1_VALUES:
                cells = []
                for b in B_VALUES:
                    v = sweep_acc(variant, k1, b, queryset, dup)
                    cells.append(f4(v) if v is not None else "—")
                lines.append(f"| **k1={k1:.2f}** | " + " | ".join(cells) + " |")
            lines.append("")
    keys = [(qs, f"{v}__k1-0.60__b-0.35__OE") for v in SWEEP_VARIANTS for qs in SWEEP_SETS]
    write(OUT / "transferability.md", lines + sources(keys))


def write_provenance() -> None:
    """Every S3 run in one table, so a reader can check a stamp without opening `runs/`."""
    lines = [
        "# S3 — provenance of every run behind `results/S3/e0/`",
        "",
        f"Generated by `{GENERATOR}`. Operating rule 1: a number without "
        "`{run_id, config SHA, code commit, query-set SHA-256}` does not exist. "
        "`src/utils/check_run_inputs.py` verifies that each of these still resolves against the tree.",
        "",
        "| run_id | queries | config SHA-256 | code commit | dirty | query-set SHA-256 |",
        "|---|---:|---|---|---|---|",
    ]
    seen = set()
    groups = [("texto", [m for m, _, _ in TEN]), ("resumen", [m for m, _, _ in TEN])]
    for variant in SWEEP_VARIANTS:
        for queryset in SWEEP_SETS:
            groups.append((queryset, [f"{variant}__k1-{k1:.2f}__b-{b:.2f}__OE"
                                      for k1 in K1_VALUES for b in B_VALUES]))
    n = 0
    for queryset, methods in groups:
        for method in methods:
            key = (queryset, method)
            if key in seen or not (RUNS / queryset / method / "run_meta.json").is_file():
                continue
            seen.add(key)
            m = meta(queryset, method)
            n += 1
            lines.append(
                f"| `{m['run_id']}` | {m['queries']:,} | `{m['config_sha256'][:16]}` | "
                f"`{m['code_commit'][:7]}` | {str(bool(m.get('code_dirty'))).lower()} | "
                f"`{m['query_set_sha256'][:16]}` |"
            )
    lines += [
        "",
        f"{n} runs. Every one `code_dirty: false`: the runners refuse to start from a dirty tree, "
        "after S3 found that a host/container line-ending disagreement had stamped a clean tree dirty "
        "(defect H5).",
        "",
        "**What these stamps do not carry**, for the four local dense arms: the `torch`, "
        "`transformers` and `sentence-transformers` versions that produced the embeddings. "
        "`index/*/meta.json` records only `{python, sklearn}` (defect H4), so for a neural arm the "
        "provenance set is incomplete and the versions live in `logs/S3/build_indexes.sh`'s captured "
        "output — a log, not a stamp. To be fixed before S12, the one run that cannot be repeated.",
    ]
    write(OUT / "run_provenance.md", lines)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    dup = flagged()
    write_ceiling(dup)
    write_replication(dup)
    write_transferability(dup)
    write_provenance()
    print(f"written: {OUT.relative_to(REPO)}")
    for path in sorted(OUT.glob("*.md")):
        print(f"  {path.name}")


if __name__ == "__main__":
    main()
