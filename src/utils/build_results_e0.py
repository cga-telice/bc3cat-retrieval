def flagged() -> set[str]:
    side = json.loads(SIDECAR.read_text(encoding="utf-8"))
    return {m for g in side["groups"].values() for m in g}


def perquery(queryset: str, method: str) -> pd.DataFrame:
    return pd.read_parquet(RUNS / queryset / method / "results_perquery.parquet")


def meta(queryset: str, method: str) -> dict:
    return json.loads((RUNS / queryset / method / "run_meta.json").read_text(encoding="utf-8"))


def scored(frame: pd.DataFrame, dup: set[str], target: str) -> pd.DataFrame:
    return frame if target == "parent" else frame[~frame["gold_item_key"].isin(dup)]


def stats(frame: pd.DataFrame, target: str, label: str) -> dict:
    col = f"{target}_acc1"
    values = frame[[col]].to_numpy()
    q = boot_query(values, label)
    c = boot_cluster(values, frame["gold_parent_key"].to_numpy(), label)
    return {
        "n": len(frame),
        "acc": float(frame[col].mean()),
        "q": ci(q[:, 0]),
        "c": ci(c[:, 0]),
    }


def header(title: str, how: list[str]) -> list[str]:
    return [f"# S3 — {title}", "", f"Generated by `{GENERATOR}`. " + " ".join(how), ""]


def sources(keys: list[tuple[str, str]]) -> list[str]:
    lines = ["", "## Sources", "", "| run_id | queries | config SHA-256 | code commit | query-set SHA-256 |", "|---|---:|---|---|---|"]
    for queryset, method in keys:
        m = meta(queryset, method)
        lines.append(
            f"| `{m['run_id']}` | {m['queries']:,} | `{m['config_sha256'][:16]}` | "
            f"`{m['code_commit'][:7]}` | `{m['query_set_sha256'][:16]}` |"
        )
    lines += [
        "",
        f"| exclusion input | SHA-256 |",
        "|---|---|",
        f"| `OE_duplicate_texto_groups.json` | `{sha256_file(SIDECAR)[:16]}` |",
        "",
        f"Bootstrap: B = {B:,}, seed = {SEED}, percentile 95 % intervals. Split `dev`.",
    ]
    return lines


# --------------------------------------------------------------------------- E0(a) ceilings


def write_ceiling(dup: set[str]) -> None:
    lines = header(
        "E0(a): the identity ceiling, per method (`texto`, dev)",
        [
            "Each arm asked to retrieve a document when handed that document's own text. Under",
            "D-032 this is **the arm's own ceiling**, not a gate: no method is disqualified for",
            "failing to reach 1.0, but a claim that ignores its method's ceiling is.",
        ],
    )
    unavoidable = sum(len(g) - 1 for g in json.loads(SIDECAR.read_text(encoding="utf-8"))["groups"].values())
    n_all = len(perquery("texto", TEN[0][0]))
    corpus_ceiling = 1 - unavoidable / n_all
    lines += [
        f"**The corpus permits at most {corpus_ceiling:.4f} for a `texto`-only method.** 776 leaves in "
        "292 groups share a `texto` with a sibling, so one member of each group can be found and the "
        f"rest cannot: {unavoidable} unavoidable misses out of {n_all:,}. Item-level scoring excludes "
        "those queries (D-033), which is why the scored column below has a ceiling of exactly **1.0** "
        "and headroom is the observed value itself.",
        "",
        "| method | | item, all queries | item, scored | n scored | CI (query) | CI (concept) | parent | CI (query) |",
        "|---|---|---:|---:|---:|---|---|---:|---|",
    ]
    for method, short, oracle in TEN:
        frame = perquery("texto", method)
        kept = scored(frame, dup, "item")
        s = stats(kept, "item", f"ceil|{short}")
        p = stats(frame, "parent", f"ceilp|{short}")
        mark = "**oracle**" if oracle else ""
        lines.append(
            f"| `{short}` | {mark} | {f4(float(frame['item_acc1'].mean()))} | **{f4(s['acc'])}** | "
            f"{s['n']:,} | {fci(s['q'])} | {fci(s['c'])} | {f4(p['acc'])} | {fci(p['q'])} |"
        )
    lines += [
        "",
        "## The oracle arms' advantage is exactly the 776 undecidable queries, and nothing else",
        "",
        "Splitting each arm's identity performance at the duplicate groups makes the structure plain. "
        "One member of each group can be found and the rest cannot — **from the text**. An arm that "
        "also indexes the record's parsed `parameters` is not bound by that, because the parameters "
        "differ even where the `texto` does not.",
        "",
        "| method | | on the 34,646 decidable | on the 776 undecidable | vs chance (292) |",
        "|---|---|---:|---:|---:|",
    ]
    for method, short, oracle in TEN:
        frame = perquery("texto", method)
        dups = frame[frame["gold_item_key"].isin(dup)]
        got = int(dups["item_acc1"].sum())
        kept = scored(frame, dup, "item")
        lines.append(
            f"| `{short}` | {'**oracle**' if oracle else ''} | {f4(float(kept['item_acc1'].mean()))} | "
            f"{got:,} of {len(dups):,} | {got - 292:+,d} |"
        )
    lines += [
        "",
        "**`bm25_unigram_params` resolves 776 of 776** — every one. `tfidf_phrases_replace` resolves "
        "676. **No text-only arm beats chance**, and the three that sit at their corpus ceiling land on "
        "it almost exactly: 292, 293, 293 against an expectation of 292. So the two oracle arms are not "
        "*better* at identity; they are answering a different question, one in which the answer is "
        "determined. A text-only method cannot do this even in principle.",
        "",
        "The arms *below* chance are below it for a different reason, and the column should not be "
        "read as tie-breaking skill: `bm25_unigram` at 244, `dense_e5` at 125, the GTE pair at 104 and "
        "`bge_m3_sparse` at 65 frequently retrieve no member of the group at all, so they lose these "
        "queries the same way they lose their others rather than by picking the wrong sibling.",
        "",
        "D-010 was argued from the code in S2 and measured on query sets. This is a third and sharper "
        "confirmation: **776 of 776 against a chance baseline of 292.** Neither oracle arm may be "
        "quoted without its text-only counterpart.",
        "",
        "And on the decidable population the ranking is not what the full-population column suggests: "
        "`dense_es_hiiamsid` reads its own target back **perfectly** (1.0000), above both oracle arms. "
        "A Spanish sentence-similarity model that the previous submission never reported has the "
        "cleanest identity behaviour in the set — which says nothing yet about retrieval under "
        "variation, where it collapses to 0.0096 on `resumen`, and everything about why a ceiling must "
        "be measured per method before any degradation is read against it (D-032).",
        "",
        "## Two arms are far below their corpus ceiling, and for different reasons",
        "",
        "`bge_m3_sparse` at 0.0509 cannot retrieve a document from that document's own text. The gold "
        "sits at rank 2–6 with no ties, and the indexed vectors are **not** L2-normalised (norms "
        "0.47–1.09, a 2.3× spread) against a raw dot product — so a sibling with a heavier vector "
        "out-scores the document against its own. That is BGE-M3's intended lexical scoring, so it is "
        "a ceiling rather than a defect, but it leaves the arm no headroom to lose and every later "
        "figure for it is read against 0.0509.",
        "",
        "`bm25_unigram` at 0.8998 is below for a different reason, diagnosed in S2's "
        "`identity_misses.md`: token subsumption between maintenance bands, not duplication. The two "
        "GTE arms and `dense_e5` are below because near-identical sibling texts embed to near-"
        "identical vectors — the parametric collapse, at the encoder.",
    ]
    write(OUT / "ceiling.md", lines + sources([("texto", m) for m, _, _ in TEN]))


