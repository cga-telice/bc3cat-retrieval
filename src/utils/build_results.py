"""Generate the derived tables a sprint report points at — never hand-edited.

Reads `runs/` and writes `docs/synthetic-oe/results/<sprint>/`. Everything here is
regenerable from the runs alone, which is what makes the report quotable: the report names
a figure, this produces it, and the two cannot drift because only one of them is written.

    python src/utils/build_results.py --sprint S1
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RUNS = REPO / "runs"
RESULTS = REPO / "docs" / "synthetic-oe" / "results"
FIXTURE = REPO / "tests" / "fixtures" / "oeb_bm25_pre_migration"

HEADLINE_SCOPES = ("overall", "has_numbers", "no_numbers")


def load_runs() -> list[dict]:
    runs = []
    for meta_path in sorted(RUNS.glob("*/*/*/run_meta.json")):
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        metrics_path = meta_path.parent / "metrics_dual.json"
        meta["_metrics"] = (
            json.loads(metrics_path.read_text(encoding="utf-8")) if metrics_path.exists() else []
        )
        runs.append(meta)
    return runs


def write_provenance(runs: list[dict], out: Path) -> None:
    lines = [
        "# S1 — run provenance",
        "",
        "Generated by `src/utils/build_results.py`. Every run's four-part stamp, as the run",
        "itself recorded it at execution time (operating rule 1). Digests are truncated here;",
        "the full values are in each run's `run_meta.json`.",
        "",
        "| run_id | queries | split | config SHA-256 | code commit | query-set SHA-256 | dirty |",
        "|---|---:|---|---|---|---|---|",
    ]
    for run in runs:
        lines.append(
            f"| `{run['run_id']}` | {run['queries']:,} | {run['split']} | "
            f"`{run['config_sha256'][:16]}` | `{run['code_commit'][:7]}` | "
            f"`{run['query_set_sha256'][:16]}` | {'yes' if run.get('code_dirty') else 'no'} |"
        )

    lines += [
        "",
        "## What each run read and wrote",
        "",
        "| run_id | query table | gold column | dropped | K | batch | elapsed (s) |",
        "|---|---|---|---:|---:|---|---:|",
    ]
    for run in runs:
        lines.append(
            f"| `{run['run_id']}` | `{Path(run['query_path']).name}` | `{run['gold_column']}` | "
            f"{run['dropped']} | {run['K']} | {run['batch_size'] or 'default'} | {run['elapsed_s']} |"
        )
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_headline(runs: list[dict], out: Path) -> None:
    lines = [
        "# S1 — headline figures per run",
        "",
        "Generated by `src/utils/build_results.py` from each run's `metrics_dual.json`.",
        "",
        "**These are not results.** S1 is plumbing: it changed no method and tuned nothing,",
        "and its design says so. They are evidence that the harness runs end to end, and the",
        "reference S2 will measure against. Nothing here is a finding about retrieval.",
        "",
        "| run_id | target | queries | Acc@1 | Recall@5 | Recall@10 | MRR | nDCG@10 |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for run in runs:
        for row in run["_metrics"]:
            if row["scope"] != "overall":
                continue
            lines.append(
                f"| `{run['run_id']}` | {row['target']} | {int(row['queries']):,} | "
                f"{row['Acc@1']:.4f} | {row['Recall@5']:.4f} | {row['Recall@10']:.4f} | "
                f"{row['MRR']:.4f} | {row['nDCG@10']:.4f} |"
            )
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_slices(runs: list[dict], out: Path) -> None:
    lines = [
        "# S1 — every slice, every run",
        "",
        "Generated by `src/utils/build_results.py`. Exists to show the slice machinery",
        "produces what exit criterion 7 asks for, not to be read as results.",
        "",
        "| run_id | target | scope | queries | Acc@1 | MRR | nDCG@10 |",
        "|---|---|---|---:|---:|---:|---:|",
    ]
    for run in runs:
        for row in run["_metrics"]:
            if row["scope"] in HEADLINE_SCOPES:
                continue
            lines.append(
                f"| `{run['run_id']}` | {row['target']} | `{row['scope']}` | "
                f"{int(row['queries']):,} | {row['Acc@1']:.4f} | {row['MRR']:.4f} | "
                f"{row['nDCG@10']:.4f} |"
            )
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_fixture_check(out: Path) -> None:
    import sys

    sys.path.insert(0, str(REPO / "src"))
    from utils.compare_metrics import COMPARED, diff_metrics

    expected = json.loads((FIXTURE / "metrics_dual.json").read_text(encoding="utf-8"))
    stamp = json.loads((FIXTURE / "STAMP.json").read_text(encoding="utf-8"))
    migrated_path = RUNS / "OEB" / "resumen" / "bm25_unigram_params__k1-0.60__b-0.35" / "metrics_dual.json"
    actual = json.loads(migrated_path.read_text(encoding="utf-8"))

    differences = diff_metrics(expected, actual, allow_extra_scopes=True)
    by_key = {(r["target"], r["scope"]): r for r in actual}

    lines = [
        "# S1 — the golden fixture, before and after the migration",
        "",
        "Generated by `src/utils/build_results.py`.",
        "",
        f"The fixture was captured at code commit `{stamp['code_commit'][:7]}`, before any",
        "notebook was migrated, from a tree with no uncommitted change under `src/` or",
        f"`configs/`. Execution: `RANDOM_SAMPLE={stamp['execution']['RANDOM_SAMPLE']}`,",
        f"`random_state={stamp['execution']['random_state']}`, `K={stamp['execution']['K']}`.",
        "",
        "| target | scope | metric | before | after | moved |",
        "|---|---|---|---:|---:|---|",
    ]
    for row in expected:
        after = by_key.get((row["target"], row["scope"]), {})
        for field in COMPARED:
            before_value, after_value = row.get(field), after.get(field)
            moved = "**yes**" if before_value != after_value else "no"
            fmt = (lambda v: f"{v:,.0f}") if field == "queries" else (lambda v: f"{v:.10f}")
            lines.append(
                f"| {row['target']} | {row['scope']} | {field} | {fmt(before_value)} | "
                f"{fmt(after_value)} | {moved} |"
            )

    lines += [
        "",
        f"**Differences reported by `diff_metrics`: {len(differences) or 'none'}.**",
    ]
    if differences:
        lines += ["", "```"] + differences + ["```"]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sprint", required=True)
    args = ap.parse_args()

    out_dir = RESULTS / args.sprint
    out_dir.mkdir(parents=True, exist_ok=True)

    runs = load_runs()
    if not runs:
        raise SystemExit(f"no runs under {RUNS}")

    write_provenance(runs, out_dir / "run_provenance.md")
    write_headline(runs, out_dir / "headline_figures.md")
    write_slices(runs, out_dir / "slices.md")
    write_fixture_check(out_dir / "fixture_check.md")

    print(f"{len(runs)} runs -> {out_dir.relative_to(REPO)}")
    for path in sorted(out_dir.glob("*.md")):
        print(f"  {path.name} ({path.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
