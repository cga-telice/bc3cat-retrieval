"""Build docs/synthetic-oe/results/S3/ — S3 work item 3, the duplicate-aware re-score.

D-033: **item-level scoring excludes the queries whose gold leaf belongs to a
`duplicate_texto_group`**, because such a query is undecidable from the indexed field — two
leaves carry the same `texto`, so no ranking can prefer the right one. Parent-level scoring
excludes nothing, since no group crosses a concept. The corpus is untouched: all 70,242 leaves
stay indexed and the duplicated leaves remain as distractors, because ambiguity is a property of
the gold, not of the pool.

This re-scores S2's fifteen runs on that population. It performs **no retrieval**: S2's own
`results_perquery.parquet` holds each query's metrics at both levels, and the mean of those
columns reproduces `metrics_dual.json` to within 5e-5 for all fifteen runs — asserted here before
anything is filtered, because that equality is the whole licence for re-scoring by subsetting. So
these are the harness's own `ranx`-consistent numbers on a smaller population, not a second
implementation of the metrics.

Nothing under `runs/` is read for anything but reading, and `results/S2/` is left exactly as it
is: it remains the record of what S2 *reported*, and the difference between the two directories is
itself a result.

Every helper — bootstrap, clustering, Holm/BH, formatting, provenance — is imported from
`build_results_s2` rather than copied, so the two sets of tables cannot drift apart in their
definitions. Same seed, same B.

    python src/utils/build_results_s3.py
"""

