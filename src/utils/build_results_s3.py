def header(title: str, how: list[str]) -> list[str]:
    return [
        f"# S3 — S2 re-scored, {title}",
        "",
        f"Generated by `{GENERATOR}` from S2's runs; no retrieval was performed. " + " ".join(how),
        "",
    ]


def sources(runs: dict, keys: list[tuple[str, str]]) -> list[str]:
    lines = [
        "",
        "## Sources",
        "",
        "| run_id | config SHA-256 | code commit | query-set SHA-256 |",
        "|---|---|---|---|",
    ]
    for key in keys:
        m = runs[key]
        lines.append(
            f"| `{m['run_id']}` | `{m['config_sha256'][:16]}` | `{m['code_commit'][:7]}` | "
            f"`{m['query_set_sha256'][:16]}` |"
        )
    lines += [
        "",
        f"| exclusion input | SHA-256 |",
        "|---|---|",
        f"| `OE_duplicate_texto_groups.json` | `{sha256_file(SIDECAR)[:16]}` |",
        "",
        f"Bootstrap: B = {B:,}, seed = {SEED}, percentile 95 % intervals.",
    ]
    return lines


# --------------------------------------------------------------------------- the population


def duplicate_leaves() -> set[str]:
    side = json.loads(SIDECAR.read_text(encoding="utf-8"))
    flagged = {member for group in side["groups"].values() for member in group}
    if len(flagged) != side["n_leaves"]:
        raise SystemExit(
            f"{SIDECAR.name}: n_leaves says {side['n_leaves']}, groups hold {len(flagged)}"
        )
    return flagged


def assert_perquery_reproduces_metrics(runs: dict) -> None:
    """The licence for subsetting: the mean of the per-query columns *is* the reported metric.

    Checked on the full population, before any filter. If this ever fails, re-scoring by
    subsetting is invalid and the sprint must recompute from the top-100 lists instead.
    """
    problems = []
    for queryset in QUERYSETS:
        for method in METHODS:
            meta = runs[(queryset, method)]
            perquery = meta["_perquery"]
            for target, column in (("item", "item_acc1"), ("parent", "parent_acc1")):
                observed = float(perquery[column].mean())
                reported = metrics_dual_overall(meta, target)
                if not np.isfinite(reported) or abs(observed - reported) > 5e-5:
                    problems.append(
                        f"{queryset}/{SHORT[method]} {target}: perquery {observed:.6f} vs "
                        f"metrics_dual {reported:.6f}"
                    )
    if problems:
        raise SystemExit(
            "per-query means do not reproduce metrics_dual; subsetting would not be the "
            "harness's own metric:\n  " + "\n  ".join(problems)
        )


def scored(perquery: pd.DataFrame, flagged: set[str], target: str) -> pd.DataFrame:
    """The population a `target`-level figure is computed on (D-033)."""
    if target == "parent":
        return perquery
    return perquery[~perquery["gold_item_key"].isin(flagged)]


